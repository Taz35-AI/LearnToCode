export const MEDIA_BY_SLUG: ReadonlyMap<string, MediaAsset> = new Map(
  MEDIA_ASSETS.map((asset) => [asset.slug, asset]),
);

export function getMedia(slug: string): MediaAsset | undefined {
  return MEDIA_BY_SLUG.get(slug);
}

/**
 * Every public path this library owns, including responsive variants, posters
 * and caption files. `verify-media.mjs` checks each one exists on disk, and the
 * evaluator uses it to tell a learner when a media path is broken.
 */
export function allMediaPaths(): string[] {
  const paths = new Set<string>();
  for (const asset of MEDIA_ASSETS) {
    paths.add(asset.path);
    for (const s of asset.srcset) paths.add(s.path);
    for (const f of asset.formats) paths.add(f.path);
    if (asset.posterPath) paths.add(asset.posterPath);
    if (asset.captionsPath) paths.add(asset.captionsPath);
  }
  paths.add('/learning-media/favicon.svg');
  paths.add('/learning-media/favicon.png');
  return [...paths].sort();
}

