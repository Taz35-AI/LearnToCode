function iconAsset(slug: string): MediaAsset {
  const path = `/learning-media/icons/${slug}.svg`;
  const name = slug.replace(/-/g, ' ');
  return {
    slug: `icon-${slug}`,
    kind: 'icon',
    title: `${name.charAt(0).toUpperCase()}${name.slice(1)} icon`,
    description: `A simple line icon of a ${name}, drawn on a 24 by 24 grid.`,
    path,
    width: 24,
    height: 24,
    srcset: [],
    formats: [{ path, type: 'image/svg+xml' }],
    // Icons that sit beside a text label are decorative and take alt="".
    suggestedAlt: '',
    isDecorativeExample: true,
    tags: ['icon', 'ui', slug],
    attribution: cc0(`${name} icon`, path, 'Hand-authored SVG path data.'),
  };
}

