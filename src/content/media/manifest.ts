function sceneAsset(spec: SceneSpec): MediaAsset {
  const heightFor = (w: number) =>
    spec.aspect === 'landscape'
      ? Math.round((w * 1067) / 1600)
      : spec.aspect === 'portrait'
        ? Math.round((w * 1600) / 1067)
        : w;

  const srcset: MediaSource[] = WIDTHS.map((w) => ({
    path: `/learning-media/images/${spec.slug}-${w}.jpg`,
    type: 'image/jpeg',
    width: w,
    height: heightFor(w),
  }));

  const formats: MediaSource[] = WIDTHS.map((w) => ({
    path: `/learning-media/images/${spec.slug}-${w}.webp`,
    type: 'image/webp',
    width: w,
    height: heightFor(w),
  }));

  return {
    slug: spec.slug,
    kind: 'photo',
    title: spec.title,
    description: spec.description,
    path: `/learning-media/images/${spec.slug}.jpg`,
    width: 1200,
    height: heightFor(1200),
    srcset,
    formats,
    suggestedAlt: spec.suggestedAlt,
    isDecorativeExample: spec.decorative ?? false,
    tags: spec.tags,
    attribution: cc0(spec.title, `/learning-media/images/${spec.slug}.jpg`,
      'Rendered procedurally from code; not a photograph of a real place or person.'),
  };
}

