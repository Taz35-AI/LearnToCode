function diagramAsset(spec: DiagramSpec): MediaAsset {
  const path = `/learning-media/svg/${spec.slug}.svg`;
  return {
    slug: spec.slug,
    kind: 'illustration',
    title: spec.title,
    description: spec.description,
    path,
    srcset: [],
    formats: [{ path, type: 'image/svg+xml' }],
    suggestedAlt: spec.suggestedAlt,
    isDecorativeExample: spec.decorative ?? false,
    tags: spec.tags,
    attribution: cc0(spec.title, path, 'Hand-authored SVG markup, written for this course.'),
  };
}

