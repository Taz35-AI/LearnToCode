/**
 * The learning media library.
 *
 * Every asset listed here was created from scratch by `scripts/generate_media.py`
 * in this repository. Nothing is downloaded at build or run time, nothing is
 * hotlinked, and no third-party work is included. All assets are dedicated to
 * the public domain under CC0-1.0, which is recorded per-asset below and
 * surfaced to learners on the in-app `/media` page.
 *
 * `npm run media:verify` walks this file and fails the build if any path,
 * srcset entry, poster or captions file is missing from `public/`.
 */

import type { MediaKind } from '@/lib/supabase/database.types';

export interface MediaSource {
  /** Public path, always beginning `/learning-media/`. */
  path: string;
  /** MIME type, used for `<source type="…">` in lessons. */
  type: string;
  width?: number;
  height?: number;
}

export interface MediaAttribution {
  assetTitle: string;
  creator: string;
  source: string;
  sourceUrl: string | null;
  licence: string;
  licenceUrl: string | null;
  attributionText: string;
  localPath: string;
  retrievedOn: string;
  notes?: string;
}

export interface MediaAsset {
  slug: string;
  kind: MediaKind;
  title: string;
  description: string;
  /** The path used in a plain `src`, guaranteed to exist. */
  path: string;
  width?: number;
  height?: number;
  durationSeconds?: number;
  /** Responsive candidates, widest last. */
  srcset: MediaSource[];
  /** Alternative encodings for `<picture>` / `<video>` / `<audio>`. */
  formats: MediaSource[];
  posterPath?: string;
  captionsPath?: string;
  /** A model answer for `alt`, used in lessons and the media picker. */
  suggestedAlt: string;
  /** True when the asset is the course's example of a *decorative* image. */
  isDecorativeExample: boolean;
  tags: string[];
  attribution: MediaAttribution;
}

const RETRIEVED = '2026-07-27';

function cc0(assetTitle: string, localPath: string, notes?: string): MediaAttribution {
  return {
    assetTitle,
    creator: 'HTML Hero (generated by scripts/generate_media.py)',
    source: 'Created for this project',
    sourceUrl: null,
    licence: 'CC0-1.0 (public domain dedication)',
    licenceUrl: 'https://creativecommons.org/publicdomain/zero/1.0/',
    attributionText:
      'Original artwork created for HTML Hero and released under CC0-1.0. ' +
      'No attribution is required, but it is welcome.',
    localPath,
    retrievedOn: RETRIEVED,
    ...(notes ? { notes } : {}),
  };
}

